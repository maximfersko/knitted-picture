        public const int W = 5;
        public const int H = 7;

        /// <summary>Ширина строки в пикселях при масштабе scale.</summary>
        public static int Measure(string text, int scale) => text.Length * (W + 1) * scale;

        /// <summary>Написать строку; x, y — левый верх (y растра растёт вверх, поэтому рисуем от верха вниз).</summary>
        public static void Draw(Raster r, string text, int x, int top, Rgba color, int scale = 2)
        {
            var cx = x;
            foreach (var raw in text.ToUpperInvariant())
            {
                if (Glyphs.TryGetValue(raw, out var rows))
                {
                    for (var gy = 0; gy < H; gy++)
                    {
                        for (var gx = 0; gx < W; gx++)
                        {
                            if (rows[gy][gx] != '#')
                            {
                                continue;
                            }

                            for (var sy = 0; sy < scale; sy++)
                            {
                                for (var sx = 0; sx < scale; sx++)
                                {
                                    r.Blend(cx + gx * scale + sx, top - (gy * scale + sy), color);
                                }
                            }
                        }
                    }
                }

                cx += (W + 1) * scale;
            }
        }
