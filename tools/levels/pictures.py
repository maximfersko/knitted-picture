if __name__ == "__main__":
    bad = False
    for i, (name, pal, rows) in sorted(P.items()):
        w = len(rows[0])
        for y, r in enumerate(rows):
            if len(r) != w:
                print(f"{i} {name}: ряд {y} длина {len(r)} != {w}: {r}")
                bad = True
        miss = set("".join(rows)) - set(pal)
        if miss:
            print(f"{i} {name}: нет в палитре {miss}")
            bad = True
        unused = set(pal) - set("".join(rows))
        motif = sum(ch != "." for r in rows for ch in r)
        print(f"{i:2} {name:14} {w}x{len(rows)} мотив {motif:3} цветов {len(set(''.join(rows)))-1} {'неисп. '+str(unused) if unused else ''}")
    print("BAD" if bad else "OK")
