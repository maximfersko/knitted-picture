def stripes_balloon():
    cols = "rybrybbyrbyr"
    widths = [4, 8, 10, 12, 12, 12, 12, 10, 8, 6]
    rows = []
    for w in widths:
        pad = (12 - w) // 2
        rows.append("." * pad + cols[pad:pad + w] + "." * (12 - pad - w))
    rows += ["..l......l..", "...l....l...", "...kKkKkK...", "...KkKkKk..."]
    return rows

def umbrella():
    widths = [6, 10, 12, 14, 14]
    rows = []
    for w in widths:
        pad = (14 - w) // 2
        row = ""
        for c in range(14):
            if pad <= c < pad + w:
                row += "r" if (c // 2) % 2 == 0 else "w"
            else:
                row += "."
        rows.append(row)
    rows += [
        "rr.ww.rr.ww.rr",
        "d......h......",
        ".......h....d.",
        "..d....h......",
        ".......h.....d",
        "d......h..d...",
        ".....h.h......",
        "......h.......",
    ]
    return rows

