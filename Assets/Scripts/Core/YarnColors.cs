#nullable enable

using System;
using System.Linq;

namespace KnittedPicture.Core
{
    /// <summary>
    /// Цвета клубков. Все уровни берут цвета только отсюда: 12 цветов, которые различаются с первого взгляда.
    /// Оттенков одного цвета нет (тёмно- и светло-зелёный, оранжевый и рыжий): по отзывам они путали —
    /// клубок «почти того же» цвета ставили на станок, а он оказывался не нужен. Минимальная разница
    /// между любыми двумя цветами — ΔE2000 ≈ 21 (заметно с первого взгляда, на телефоне и при ярком солнце).
    /// Цвет ткани (фона) тоже отсюда: «чужая пряжа» и клубки «в сеточку» бывают цвета фона.
    /// </summary>
    public static class YarnColors
    {
        public static readonly (string Hex, string Name)[] All =
        {
            ("#FFFFFF", "Белый"),
            ("#26262E", "Чёрный"),
            ("#8C9198", "Серый"),
            ("#E8333A", "Красный"),
            ("#FF8A1F", "Оранжевый"),
            ("#FFD419", "Жёлтый"),
            ("#2DB34A", "Зелёный"),
            ("#4CC3F5", "Голубой"),
            ("#2552D9", "Синий"),
            ("#B04FD8", "Фиолетовый"),
            ("#FF6FB7", "Розовый"),
            ("#8A5530", "Коричневый"),
        };

        /// <summary>Цвет из набора (регистр не важен).</summary>
        public static bool Contains(string hex) => All.Any(c => string.Equals(c.Hex, hex, StringComparison.OrdinalIgnoreCase));
    }
}
